class ResultsAnalyzer:
    """Analyzer for experiment results"""

    def __init__(self, experiment_dir: str):
        """
        Initialize the analyzer.

        Args:
            experiment_dir: Experiment folder containing algorithm_logs/
        """
        self.experiment_dir = Path(experiment_dir)
        self.algorithm_logs_dir = self.experiment_dir / "algorithm_logs"
        self.results: List[ExperimentResult] = []
        self.has_flops_module = False
        self.has_hardware_module = False
        self.config: Dict[str, Any] = {}  # Experiment configuration

    def load_results(self) -> bool:
        """
        Load all results from log files.

        Returns:
            True if logs were loaded successfully, False otherwise
        """
        # Load config.yaml file
        self._load_config_yaml()
        print("[INFO] Analyzing results...")

        if not self.algorithm_logs_dir.exists():
            print(f"  algorithm_logs folder not found in {self.experiment_dir}")
            return False

        # Load accuracies
        accuracies = self._load_accuracies()
        if not accuracies:
            print(f"  No acc_report.txt file found")
            return False

        scores = self._load_scores()
        has_score_file = bool(scores)
        if has_score_file:
            print(f"  score_report.txt file found, will use scores calculated during training")
        else:
            print("  No score_report.txt file found, score will be recomputed from module logs when possible")

        # Load hyperparameters
        hyperparams_list = self._load_hyperparams()

        # Load FLOPS data
        flops_data = self._load_flops_data()
        if flops_data:
            self.has_flops_module = True

        # Load hardware data
        hw_data = self._load_hardware_data()
        if hw_data:
            self.has_hardware_module = True

        # Load per-iteration timing data (see components/controller.py's log_timing)
        timing_map = self._load_timing_data()

        # Combine the data
        max_iterations = max(
            len(accuracies),
            len(hyperparams_list),
            len(flops_data) if flops_data else 0,
            len(hw_data) if hw_data else 0,
            max(timing_map.keys()) if timing_map else 0,
        )
        for i in range(max_iterations):
            timing_row = timing_map.get(i + 1)
            result = ExperimentResult(
                iteration=i + 1,
                accuracy=accuracies[i] if i < len(accuracies) else None,
                flops=flops_data[i][1] if flops_data and i < len(flops_data) else None,
                nparams=flops_data[i][0] if flops_data and i < len(flops_data) else None,
                latency=hw_data[i][0] if hw_data and i < len(hw_data) else None,
                hw_cost=hw_data[i][1] if hw_data and i < len(hw_data) else None,
                hw_total_cost=hw_data[i][2] if hw_data and i < len(hw_data) else None,
                hw_config=hw_data[i][3] if hw_data and i < len(hw_data) else None,
                score=scores[i] if scores and i < len(scores) else None,
                w_flops=self.config.get("w_flops") if self.has_flops_module else None,
                hyperparams=hyperparams_list[i] if i < len(hyperparams_list) else None,
                total_time=self._safe_float(timing_row.get("total_time")) if timing_row else None,
                search_time=self._safe_float(timing_row.get("search_time")) if timing_row else None,
                symbolic_time=self._safe_float(timing_row.get("symbolic_time")) if timing_row else None,
                training_time=self._safe_float(timing_row.get("training_time")) if timing_row else None,
                module_times=self._extract_module_times(timing_row) if timing_row else None,
            )

            # Calculate score: -accuracy if no modules are present
            if result.score is None:
                result.score = self._recompute_score(result)

            self.results.append(result)

        return True

    def _load_accuracies(self) -> List[Optional[float]]:
        """Load accuracies from acc_report.txt file"""
        acc_file = self.algorithm_logs_dir / "acc_report.txt"
        if not acc_file.exists():
            return []

        accuracies = []
        try:
            with open(acc_file, 'r') as f:
                for line in f:
                    line = line.strip()
                    if line == "None" or line == "":
                        accuracies.append(None)
                    else:
                        accuracies.append(float(line))
        except Exception as e:
            print(f"  Error reading {acc_file}: {e}")
            return []

        return accuracies

    def _load_scores(self) -> List[Optional[float]]:
        """Load scores from score_report.txt file"""
        score_file = self.algorithm_logs_dir / "score_report.txt"
        if not score_file.exists():
            return []

        scores = []
        try:
            with open(score_file, 'r') as f:
                for line in f:
                    line = line.strip()
                    if line == "None" or line == "":
                        scores.append(None)
                    else:
                        scores.append(float(line))
        except Exception as e:
            print(f"  Error reading {score_file}: {e}")
            return []

        return scores



    def _extract_layers_per_iteration(self, input_file):
        import re
        iteration_pattern = re.compile(r'START TRAINING ITERATION (\d+)')
        layer_pattern = re.compile(r'layer_x_block=(\d+)')


        results = {}
        current_iter = None

        with open(input_file, 'r', encoding='utf-8') as f:
            for line in f:
                iter_match = iteration_pattern.search(line)
                if iter_match:
                    current_iter = int(iter_match.group(1))
                    continue

                if current_iter is not None:
                    layer_match = layer_pattern.search(line)
                    if layer_match:
                        # prende sempre l'ULTIMO
                        results[current_iter] = int(layer_match.group(1))

        return results


    def _get_out_file(self):
        out_files = list(Path(self.experiment_dir).glob("*.out"))

        if len(out_files) == 0:
            raise FileNotFoundError("Nessun file .out trovato in {}".format(self.experiment_dir))
        elif len(out_files) > 1:
            raise ValueError(f"Più file .out trovati: {out_files}")

        return str(out_files[0])


    def _extract_hyperparams_per_iteration(self, input_file):
        """
        Estrae, per ogni iterazione, il dizionario di hyperparametri (dalla riga
        'Chosen point: {...}' che precede 'START TRAINING ITERATION N') e il
        relativo layer_x_block (dalla riga 'Building model ... layer_x_block=N'
        che segue).
        """
        import re
        import ast

        iteration_pattern = re.compile(r'ITERATION (\d+)')
        layer_pattern = re.compile(r'layer_x_block=(\d+)')
        chosen_point_pattern = re.compile(r'Chosen point:\s*(\{.*\})')

        results = {}
        current_iter = None
        pending_hp = None  # hyperparams letti ma non ancora assegnati a un'iterazione

        with open(input_file, 'r', encoding='utf-8') as f:
            for line in f:
                # 1) riga con gli hyperparametri, arriva PRIMA dello start iteration
                cp_match = chosen_point_pattern.search(line)
                if cp_match:
                    try:
                        pending_hp = ast.literal_eval(cp_match.group(1))
                    except Exception as e:
                        print(f"  Error parsing 'Chosen point' line: {e}")
                        pending_hp = None
                    continue

                # 2) inizio nuova iterazione: assegna gli hyperparametri in sospeso
                iter_match = iteration_pattern.search(line)
                if iter_match:
                    current_iter = int(iter_match.group(1))
                    if pending_hp is not None:
                        results[current_iter] = dict(pending_hp)
                        pending_hp = None
                    continue

                # 3) layer_x_block della stessa iterazione (prende sempre l'ULTIMO)
                if current_iter is not None:
                    layer_match = layer_pattern.search(line)
                    if layer_match:
                        results.setdefault(current_iter, {})
                        results[current_iter]['layer_x_block'] = int(layer_match.group(1))

        return results


    def _get_out_file(self):
        out_files = list(Path(self.experiment_dir).glob("*.out"))

        if len(out_files) == 0:
            raise FileNotFoundError("Nessun file .out trovato in {}".format(self.experiment_dir))
        elif len(out_files) > 1:
            raise ValueError(f"Più file .out trovati: {out_files}")

        return str(out_files[0])


    def _load_hyperparams(self) -> List[Optional[Dict[str, Any]]]:
        """Load hyperparameters directly from the .out file (righe 'Chosen point:' + layer_x_block)"""
        try:
            out_file = self._get_out_file()
            hp_map = self._extract_hyperparams_per_iteration(out_file)
        except Exception as e:
            print(f"  Error reading hyperparameters from .out file: {e}")
            return []

        if not hp_map:
            print(f"  Nessun hyperparametro trovato nel file .out")
            return []

        max_iter = max(hp_map.keys())
        hyperparams = [hp_map.get(i) for i in range(max_iter + 1)]

        return hyperparams

